export function LucideByName({
  name,
  size,
  className,
}: {
  name?: string;
  size: number;
  className?: string;
}) {
  if (!name) return null;
  const Icon = LUCIDE_BY_NAME[name];
  if (!Icon) return null;
  return <Icon size={size} strokeWidth={2} aria-hidden className={className} />;
}
